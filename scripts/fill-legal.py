#!/usr/bin/env python3
"""
Проставить реквизиты ООО «АНГЕЛ-ДЕНТ» на все страницы Венеции.

Клиника работает под тем же юрлицом, что Ангел-Дент и Версаль
(подтверждено владельцем 10.08.2026). Реквизиты сверены с выпиской из
ЕГРЮЛ № ЮЭ9965-26-154952194 от 13.08.2026 — она лежит в репозитории
Ангела: `_materials/docs/egrul-angel-dent-2026-08-13.pdf`.

Что делает:
- в футере каждой страницы заменяет `<!-- TODO: юрлицо… -->` на строку
  реквизитов (как в футере Версаля);
- на `legal.html` заменяет абзац-заглушку на блок «Сведения о
  медицинской организации».

Идемпотентно: повторный запуск ничего не меняет (ищет ровно заглушки).

  python3 scripts/fill-legal.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TODO_FOOTER = '<!-- TODO: юрлицо, ИНН/ОГРН и лицензия клиники «Венеция» — вписать при получении -->'
FOOTER = ('ООО «АНГЕЛ-ДЕНТ»<br>ИНН 5012077543 · КПП 504101001 · ОГРН 1135012000936<br>'
          'Юр. адрес: 143968, Московская область, г. Реутов, ул. Победы, д. 22, помещение V<br>'
          'Лицензия № Л041-01162-50/00299266 от 19.07.2016, выдана Министерством '
          'здравоохранения Московской области<br>')

TODO_LEGAL = ('<p><em>Сведения о юридическом лице, ИНН/ОГРН и медицинской лицензии '
              'публикуются на этой странице по мере оформления документов клиники.</em></p>'
              '<!-- TODO: юрлицо, ИНН, ОГРН, адрес, лицензия клиники «Венеция» -->')
LEGAL = '''<ul class="diamond-list">
      <li><strong>Полное наименование:</strong> Общество с ограниченной ответственностью «АНГЕЛ-ДЕНТ»</li>
      <li><strong>Сокращённое наименование:</strong> ООО «АНГЕЛ-ДЕНТ»</li>
      <li><strong>Юридический адрес:</strong> 143968, Московская область, г. Реутов, ул. Победы, д. 22, помещение V</li>
      <li><strong>ИНН:</strong> 5012077543 · <strong>КПП:</strong> 504101001</li>
      <li><strong>ОГРН:</strong> 1135012000936, дата регистрации 15.02.2013</li>
      <li><strong>Основной вид деятельности:</strong> 86.23 — стоматологическая практика</li>
      <li><strong>Генеральный директор:</strong> Геворкян Санатрук Иванович</li>
    </ul>
    <h2>Медицинская лицензия</h2>
    <ul class="diamond-list">
      <li><strong>Номер лицензии:</strong> Л041-01162-50/00299266 от 19.07.2016</li>
      <li><strong>Лицензирующий орган:</strong> Министерство здравоохранения Московской области</li>
      <li><strong>Срок действия:</strong> бессрочно</li>
    </ul>
    <p>Копию лицензии с приложениями и другие документы клиники можно посмотреть на ресепшене — по требованию выдаём копию.</p>'''


def main() -> int:
    check = '--check' in sys.argv
    changed = []
    for p in sorted(ROOT.rglob('*.html')):
        # privacy.html правится отдельно: там та же заглушка стоит внутри
        # абзаца «Оператор», и список с заголовком «Медицинская лицензия»
        # разорвал бы <p> и сбил нумерацию разделов политики.
        if '_materials' in p.parts or p.name == 'privacy.html':
            continue
        s = p.read_text(encoding='utf-8')
        out = s.replace(TODO_FOOTER, FOOTER).replace(TODO_LEGAL, LEGAL)
        if out != s:
            changed.append(p.relative_to(ROOT))
            if not check:
                p.write_text(out, encoding='utf-8')

    left = [p.relative_to(ROOT) for p in ROOT.rglob('*.html')
            if '_materials' not in p.parts and 'юрлицо' in p.read_text(encoding='utf-8')]
    print(f'{"нашлось" if check else "обновлено"}: {len(changed)} файлов')
    if left:
        print('остались заглушки:', ', '.join(map(str, left)))
    return 1 if (check and changed) else 0


if __name__ == '__main__':
    sys.exit(main())
