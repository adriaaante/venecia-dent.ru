def export():
    up = {k: url for k, mid, code, url in
          json.load(open(os.path.join(HERE, '_uploads.json')))}
    items = []
    for key, title, imgs, text in POSTS:
        text = text.strip()
        assert len(text) <= 3000, (key, len(text))
        assert len(imgs) <= 4, key
        items.append({'key': key, 'title': title, 'imgs': [up[i] for i in imgs],
                      'text': text, 'len': len(text)})
    json.dump({'title': 'Публикации (новости)', 'items': items},
              open(os.path.join(HERE, 'posts.json'), 'w'), ensure_ascii=False, indent=1)
    for it in items:
        print(f"{it['key']:9s} {it['len']:4d} симв.  фото {len(it['imgs'])}  {it['title']}")


if __name__ == '__main__':
    export()
